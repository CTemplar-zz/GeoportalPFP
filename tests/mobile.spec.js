  await page.locator('#sheetClose').click();await page.locator('[data-panel="active"]').click();
  await basin.locator('[data-action="up"]').click();expect(await keys()).toEqual(initial);
  await page.locator('#sheetClose').click();await page.locator('[data-panel="more"]').click();await page.locator('#savedViews').click();await page.locator('[data-view="0"]').click();
  await page.locator('[data-panel="active"]').click();expect(await keys()).toEqual(reordered);
  await page.reload();await page.waitForFunction(()=>MobileUI.getState().currentModule==='8');
  await page.locator('[data-panel="active"]').click();expect(await keys()).toEqual(reordered);
  await basin.locator('.layer-toggle').click();
  await page.locator('#sheetClose').click();await page.locator('[data-panel="layers"]').click();await page.locator('[data-catalog="8"]').click();
  await page.locator('.group-button[data-group="Marco espacial"]').click();await page.getByRole('switch',{name:'Cuencas Hidrográficas (Nivel 3)',exact:true}).click();
  await page.locator('#sheetClose').click();await page.locator('[data-panel="active"]').click();expect(await keys()).toEqual(reordered);
  await page.locator('#sheetClose').click();await page.locator('[data-panel="layers"]').click();await page.locator('[data-catalog="1"]').click();
  await page.locator('#sheetClose').click();await page.locator('[data-panel="active"]').click();expect(await keys()).toEqual(reordered);
  actual=await paneOrder();expect(actual.every((x,i)=>x.visible&&x.z===actual.length-i)).toBe(true);
  expect(errors).toEqual([]);
