  releaseGeometry();
  await page.waitForFunction(()=>geoData.ine_cuencas_n3?.features?.length>0);
  const paneOrder=()=>page.evaluate(()=>{
    const entries=MobileUI.getState().active;
    return entries.map(({module,id})=>{
      const layer=moduleLayers[module+':'+id],pane=map.getPane(layer.options.pane),descendants=[];
      const inspect=l=>{if(l instanceof L.Path)descendants.push(l.getElement()?.closest('[data-layer-key]')?.dataset.layerKey);if(l.eachLayer)l.eachLayer(inspect);};inspect(layer);
      return {key:module+':'+id,z:Number(pane.style.zIndex),visible:map.hasLayer(layer),descendants};
    });
  });
  let actual=await paneOrder();
  expect(actual.map(x=>x.key)).toEqual(reordered);
  expect(actual.every((x,i)=>x.visible&&x.z===actual.length-i&&x.descendants.every(key=>key===x.key))).toBe(true);
  expect(actual.find(x=>x.key==='8:ine_cuencas_n3').descendants.length).toBeGreaterThan(0);
  await expect(rows.last().locator('[data-action="down"]')).toBeDisabled();
