test('orden de teselas WMS y geometrías vectoriales en el mismo mapa',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('https://geoserver.inra.gob.bo/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#bbdddd"/></svg>'}));
  await page.goto('/');await page.locator('#enterMap').click();
  await page.waitForFunction(()=>geoData.apn&&geoData.departamentos);
  await page.locator('[data-panel="layers"]').click();await page.locator('[data-catalog="3"]').click();
  await page.locator('.group-button[data-group="SINACAR / INRA"]').click();await page.getByRole('switch',{name:'Amenaza de inundación',exact:true}).click();
  await page.locator('#sheetClose').click();await page.locator('[data-panel="active"]').click();
  const row=page.locator('.active-stack [data-layer="wms_amenaza_inundacion"]');
  const inspect=()=>page.evaluate(()=>{
    const raster=moduleLayers['3:wms_amenaza_inundacion'],vector=moduleLayers['1:departamentos'];
    let path;vector.eachLayer(child=>{if(child instanceof L.Path)path=child;});
    const rasterPane=raster.getContainer().closest('[data-layer-key]'),vectorPane=path.getElement().closest('[data-layer-key]');
    raster.bringToFront();path.bringToFront();
    return {rasterKey:rasterPane.dataset.layerKey,vectorKey:vectorPane.dataset.layerKey,above:Number(rasterPane.style.zIndex)>Number(vectorPane.style.zIndex),parent:rasterPane.parentElement===vectorPane.parentElement};
  });
  expect(await inspect()).toEqual({rasterKey:'3:wms_amenaza_inundacion',vectorKey:'1:departamentos',above:true,parent:true});
  while(!await row.locator('[data-action="down"]').isDisabled())await row.locator('[data-action="down"]').click();
  expect((await inspect()).above).toBe(false);
  while(!await row.locator('[data-action="up"]').isDisabled())await row.locator('[data-action="up"]').click();
  expect((await inspect()).above).toBe(true);
  expect(errors).toEqual([]);
});

